-- 创建 Host 范围重放状态与检查点；MySQL 建表、约束、索引同一幂等 DDL 完成。
CREATE TABLE IF NOT EXISTS fn_messaging_replay_operation
(
    Id BINARY(16) NOT NULL COMMENT '应用生成的重放操作 UUID v7',
    RequestId BINARY(16) NOT NULL COMMENT '客户端创建重试键，不作为逻辑主键',
    EventType varchar(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '权威目录中的事件类型',
    SchemaVersion int NOT NULL COMMENT '权威目录中的事件版本',
    TopicCode varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '目标 Topic 机器码',
    ConsumerName varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '原业务 Inbox 订阅名',
    RequestJson longtext NOT NULL COMMENT '不可变的规范化请求，不包含载荷或凭据',
    SnapshotJson longtext NULL COMMENT '固定资源和分区窗口及未确认意图',
    State varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '操作稳定状态码',
    AttemptCount int NOT NULL COMMENT '已开始的执行代次数',
    LeaseToken BINARY(16) NULL COMMENT '当前或最近执行代次标识',
    LeaseUntilUtc datetime(6) NULL COMMENT '执行租约失效的 UTC 时间',
    InFlightPartition int NULL COMMENT '最近尚未确认消息的分区号',
    InFlightOffset bigint NULL COMMENT '最近尚未确认消息的 Broker 位点',
    ProcessedCount bigint NOT NULL COMMENT '已持久确认的新业务提交数量',
    AlreadyProcessedCount bigint NOT NULL COMMENT '已持久确认的 Inbox 去重数量',
    RejectedCount bigint NOT NULL COMMENT '已确认拒绝的尝试次数',
    LastReasonCode varchar(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '最近状态原因的稳定机器码',
    OperatorUserId BINARY(16) NOT NULL COMMENT '创建操作的可信用户标识',
    OperatorDisplayName varchar(128) NOT NULL COMMENT '创建时的操作者显示名快照',
    Reason varchar(512) NOT NULL COMMENT '创建操作时的不可变运维理由',
    CreatedAtUtc datetime(6) NOT NULL COMMENT '操作创建的 UTC 时间',
    UpdatedAtUtc datetime(6) NOT NULL COMMENT '最近持久进度的 UTC 时间',
    CONSTRAINT PK_fn_messaging_replay_operation PRIMARY KEY (Id),
    CONSTRAINT UQ_fn_messaging_replay_operation_RequestId UNIQUE (RequestId),
    KEY IX_fn_messaging_replay_operation_CreatedAtUtc_Id (CreatedAtUtc, Id),
    CONSTRAINT CK_fn_messaging_replay_operation_State CHECK (State IN ('prepared', 'running', 'partial', 'completed', 'cancel_requested', 'cancelled', 'result_unknown', 'blocked')),
    CONSTRAINT CK_fn_messaging_replay_operation_Counts CHECK (AttemptCount >= 0 AND ProcessedCount >= 0 AND AlreadyProcessedCount >= 0 AND RejectedCount >= 0),
    CONSTRAINT CK_fn_messaging_replay_operation_Intent CHECK ((InFlightPartition IS NULL AND InFlightOffset IS NULL) OR (InFlightPartition >= 0 AND InFlightOffset >= 0)),
    CONSTRAINT CK_fn_messaging_replay_operation_Json CHECK (JSON_VALID(RequestJson) AND OCTET_LENGTH(RequestJson) <= 65536 AND (SnapshotJson IS NULL OR (JSON_VALID(SnapshotJson) AND OCTET_LENGTH(SnapshotJson) <= 65536)))
) COMMENT='Host 范围重放操作与可恢复检查点' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
