-- 冻结业务报价与资金身份；不对其他模块表建立外键。
CREATE TABLE IF NOT EXISTS fn_payment_subscription_fulfillment (
    Id binary(16) NOT NULL COMMENT '支付创建幂等身份 UUID v7',
    SubscriptionId binary(16) NOT NULL COMMENT 'Tenancy 原始订阅',
    TenantId binary(16) NOT NULL COMMENT '支付收款租户',
    BeneficiaryTenantId binary(16) NOT NULL COMMENT '权益受益租户',
    MerchantConfigId binary(16) NOT NULL COMMENT '冻结收款商户',
    AmountMinor bigint NOT NULL COMMENT '冻结最小单位金额',
    Currency varchar(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '冻结规范币种',
    EffectiveFromUtc datetime(6) NOT NULL COMMENT '权益最早生效 UTC',
    EffectiveToUtc datetime(6) NOT NULL COMMENT '权益最晚生效 UTC',
    PaymentOrderId binary(16) NULL COMMENT '实际资金订单',
    ProviderTransactionId varchar(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '已验证渠道交易标识',
    PaidAtUtc datetime(6) NULL COMMENT '已验证支付时间 UTC',
    LastRefundId binary(16) NULL COMMENT '最近成功退款身份',
    RefundAmountMinor bigint NOT NULL COMMENT '最近已验证退款金额',
    Phase varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建付款履约退款或核对阶段',
    ErrorCode varchar(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '最近稳定失败码',
    DueAtUtc datetime(6) NOT NULL COMMENT '下次恢复时间 UTC',
    LeaseId binary(16) NULL COMMENT '当前恢复租约身份',
    LeaseUntilUtc datetime(6) NULL COMMENT '当前租约到期 UTC',
    Attempt int NOT NULL COMMENT '连续恢复次数',
    CreatedAtUtc datetime(6) NOT NULL COMMENT '创建时间 UTC',
    UpdatedAtUtc datetime(6) NOT NULL COMMENT '最近更新时间 UTC',
    Version int NOT NULL COMMENT '工作项乐观并发版本',
    CONSTRAINT PK_fn_payment_subscription_fulfillment PRIMARY KEY (Id),
    KEY IX_fn_payment_subscription_fulfillment_Phase_DueAtUtc (Phase,DueAtUtc),
    KEY IX_fn_payment_subscription_fulfillment_SubscriptionId (SubscriptionId)
) COMMENT='Payments 自有订阅履约恢复与资金绑定' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
