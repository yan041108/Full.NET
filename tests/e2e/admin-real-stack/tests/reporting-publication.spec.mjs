import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import AxeBuilder from '@axe-core/playwright';
import { clickMainNavLink, expectVisibleCurrentContext, loginAsHostAdmin, loginAsHostUser } from './support/real-stack-auth.mjs';

test('Host 显式授权后，租户通过真实后台循环导出并下载工作簿', async ({ page }) => {
  test.setTimeout(120_000); const name = process.env.FULLNET_E2E_REPORTING_DEFINITION_NAME;
  const evidence = process.env.FULLNET_REPORTING_UI_EVIDENCE;
  await page.addInitScript(() => localStorage.setItem('fullnet.admin.locale', 'zh-CN'));
  await page.setViewportSize({ width: 1440, height: 1000 }); await loginAsHostAdmin(page);
  await clickMainNavLink(page, /报表定义/);
  const row = page.locator('.definitions-card .el-table__row').filter({ hasText: name }); await expect(row).toBeVisible();
  await row.getByTestId('reporting-definition-grants').click();
  const grants = page.getByRole('dialog', { name: '租户发布授权', exact: true }); await expect(grants).toBeVisible();
  await grants.getByTestId('reporting-grant-tenant').click();
  await page.getByRole('option', { name: process.env.FULLNET_E2E_REPORTING_TENANT_NAME, exact: true }).click();
  const granted = page.waitForResponse(response => response.url().includes('/tenant-grants/') && response.request().method() === 'PUT');
  await grants.getByTestId('reporting-grant-enable').click(); expect((await granted).status()).toBe(200);
  await expect(grants.getByText('已授权', { exact: true })).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running'
    && animation.effect?.getComputedTiming().iterations !== Infinity).length)).toBe(0);
  await page.screenshot({ path: path.join(evidence, 'host-grant.png') });
  const accessibility = await new AxeBuilder({ page }).include('.reporting-publication-grants').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(accessibility.violations.filter(item => ['critical', 'serious'].includes(item.impact))).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(evidence, 'host-grant-mobile.png') });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.keyboard.press('Escape'); await expect(grants).not.toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await loginAsHostUser(page, process.env.FULLNET_E2E_REPORTING_MEMBER, process.env.FULLNET_E2E_PASSWORD);
  await clickMainNavLink(page, /租户上下文/);
  const tenant = page.locator('.tenant-context-view .el-table__row').filter({ hasText: process.env.FULLNET_E2E_REPORTING_TENANT_NAME });
  const switching = page.waitForResponse(result => result.url().includes('/api/v1/tenancy/context') && result.request().method() === 'PUT');
  await tenant.getByRole('button', { name: '进入租户', exact: true }).click(); expect((await switching).status()).toBe(200);
  await expectVisibleCurrentContext(page, process.env.FULLNET_E2E_REPORTING_TENANT_NAME); await clickMainNavLink(page, /报表导出/);
  await page.getByTestId('reporting-export-create').click(); const create = page.getByRole('dialog', { name: '新建 Excel 导出', exact: true });
  await create.getByTestId('reporting-export-definition').click(); await page.getByRole('option', { name, exact: true }).click();
  const queued = page.waitForResponse(response => new URL(response.url()).pathname.replace(/\/$/, '') === '/api/v1/reporting/export-tasks' && response.request().method() === 'POST');
  await create.getByTestId('reporting-export-submit').click(); const response = await queued; expect(response.status(), await response.text()).toBe(201);
  expect((await response.json()).statusKey).toBe('queued'); await expect(create).not.toBeVisible();
  const task = page.locator('.reporting-export-tasks-view .el-table__row').filter({ hasText: name });
  await expect(task.getByText('已成功', { exact: true })).toBeVisible({ timeout: 30_000 });
  const downloading = page.waitForEvent('download'); await task.getByTestId('reporting-export-download').click();
  const file = await downloading; expect(file.suggestedFilename()).toMatch(/\.xlsx$/); expect((await readFile(await file.path())).subarray(0, 2).toString()).toBe('PK');
  await clickMainNavLink(page, /我的任务/);
  const source = page.getByTestId('my-tasks-reports'); await expect(source).toBeVisible();
  await expect(page.getByTestId('my-tasks-imports')).toHaveCount(0);
  const ownTask = source.locator('.el-table__row').filter({ hasText: name }); await expect(ownTask).toBeVisible();
  await expect(ownTask.getByText('已成功', { exact: true })).toBeVisible();
  const ownDownload = page.waitForEvent('download'); await ownTask.getByTestId('my-tasks-download').click();
  expect((await readFile(await (await ownDownload).path())).subarray(0, 2).toString()).toBe('PK');
  await ownTask.getByTestId('my-tasks-detail').click();
  const detail = page.getByRole('dialog', { name: '导出任务详情', exact: true }); await expect(detail).toBeVisible();
  await expect(detail).toContainText(name); await expect(page).toHaveURL(/taskId=/);
  await page.keyboard.press('Escape'); await expect(detail).not.toBeVisible(); await expect(page).not.toHaveURL(/taskId=/);
  await clickMainNavLink(page, /我的任务/);
  await expect(source.locator('.el-table__row').filter({ hasText: name }).getByText('已成功', { exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(evidence, 'my-tasks-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await expect(page.getByRole('button', { name: '打开主导航', exact: true }).last()).toBeVisible();
  const backdrop = page.locator('.art-admin-shell__backdrop');
  if (await backdrop.isVisible()) { await backdrop.click(); await expect(backdrop).not.toBeVisible(); }
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running'
    && animation.effect?.getComputedTiming().iterations !== Infinity).length)).toBe(0);
  await page.screenshot({ path: path.join(evidence, 'tenant-export-mobile.png') });
  const taskAccessibility = await new AxeBuilder({ page }).include('.my-tasks-view').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(taskAccessibility.violations.filter(item => ['critical', 'serious'].includes(item.impact))).toEqual([]);
});
