-- 企业申请附件与报表共用的显式交付日记；外部文件 I/O 不加入本地事务。
CREATE TABLE IF NOT EXISTS demo_enterprise_request_delivery (
    Id BINARY(16) NOT NULL COMMENT '应用生成的交付身份 UUID v7',
    TenantId BINARY(16) NOT NULL COMMENT '可信租户',
    RequestId BINARY(16) NOT NULL COMMENT '所属申请单',
    RequestKey BINARY(16) NOT NULL COMMENT '调用方幂等请求标识',
    Kind varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Attachment 或 Report',
    RequestedVersion bigint NOT NULL COMMENT '冻结主单版本',
    ActorUserId BINARY(16) NOT NULL COMMENT '原始申请主体',
    SessionId BINARY(16) NOT NULL COMMENT '原始会话',
    SecurityStamp varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '冻结安全戳',
    ActorScope varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '原始主体作用域',
    EffectiveScope varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '冻结有效租户作用域',
    SessionKind varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '刷新或 OIDC 应用会话',
    SourceDigest varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '内容或已授权单据快照摘要',
    IncludesAmounts boolean NOT NULL COMMENT '是否包含获授权金额',
    LocaleCode varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '生成文案的规范语言标签',
    FileId BINARY(16) NULL COMMENT '绑定的 Files 文件',
    FileName varchar(255) NOT NULL COMMENT '安全下载文件名',
    ContentType varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '固定或经验证的媒体类型',
    SizeBytes bigint NULL COMMENT '实际文件字节数',
    ContentHash varchar(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '待绑定产物内容摘要',
    Phase varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '持久化交付及清理状态',
    ErrorCode varchar(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '稳定失败码',
    LeaseId BINARY(16) NULL COMMENT '本轮恢复租约',
    LeaseUntilUtc datetime(6) NULL COMMENT '租约截止时间',
    Attempt int NOT NULL COMMENT '实际领取次数',
    DueAtUtc datetime(6) NOT NULL COMMENT '下一轮可执行时间',
    ExpiresAtUtc datetime(6) NOT NULL COMMENT '上传意图或报表结果截止时间',
    CreatedAtUtc datetime(6) NOT NULL COMMENT '创建时间',
    UpdatedAtUtc datetime(6) NOT NULL COMMENT '最后状态更新时间',
    Version bigint NOT NULL COMMENT '单调并发版本',
    CONSTRAINT PK_demo_enterprise_request_delivery PRIMARY KEY (Id),
    UNIQUE KEY UX_demo_enterprise_request_delivery_TenantId_RequestId__15a99a28 (TenantId, RequestId, RequestKey, Kind, ActorUserId),
    KEY IX_demo_enterprise_request_delivery_Phase_DueAtUtc_TenantId (Phase, DueAtUtc, TenantId),
    KEY IX_demo_enterprise_request_delivery_TenantId_RequestId__ee9606bc (TenantId, RequestId, Kind, CreatedAtUtc)
) COMMENT='企业申请附件和报表交付恢复日记' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
