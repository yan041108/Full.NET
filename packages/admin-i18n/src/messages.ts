export const messages: Readonly<Record<SupportedLocale, Readonly<Record<MessageKey, string>>>> = {
  'zh-CN': zhCN,
  'en-US': enUS
};

export const messageKeys = Object.freeze(
  Object.keys(zhCN) as MessageKey[]
);

/**
 * 使用命名参数生成纯文本；缺少参数时保留占位符，让测试和界面审查能发现字典错误。
 */
export function translate(
  locale: SupportedLocale,
  key: MessageKey,
  parameters: MessageParameters = {}
): string {
  return messages[locale][key].replace(
    /\{([a-zA-Z][a-zA-Z0-9]*)\}/g,
    (placeholder, name: string) => name in parameters
      ? String(parameters[name])
      : placeholder
  );
}
